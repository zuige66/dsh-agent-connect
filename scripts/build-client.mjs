/**
 * Build `client.js` for dsh-agent-connect.
 *
 * The bundle has two halves that come from different places:
 *
 * - **Data, lifted from upstream.** The thirteen channel definitions, their
 *   logos and their credit capabilities live in `dsh-our-free-model` and are
 *   validated there. `scripts/extract-data.mjs` pulls them into
 *   `src/channels.data.js` once; this script inlines that file verbatim.
 * - **Everything else, written here.** The page itself (`src/ui.js`), its
 *   styles (`src/page.css`) and the helpers it needs are this plugin's own
 *   code. The upstream presentation — a glass card grid with gradient stripes,
 *   an eleven-tab shell and a sponsor banner — is not reused.
 *
 * Output is one self-contained ModuleLoader bundle, because that is the only
 * shape the web shell loads: no imports, no build step at runtime.
 *
 * Usage:
 *   node scripts/build-client.mjs [out]
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const outFile = process.argv[2] ?? path.join(root, 'client.js')

const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')

const data = read('src/channels.data.js')
const ui = read('src/ui.js')
const css = read('src/page.css')

// The stylesheet is emitted *inside* a template literal in the output, so a
// backtick or a `${` in it would end the literal early and break the bundle.
if (css.includes('`')) throw new Error('src/page.css contains a backtick; escape it or use different quoting')
if (css.includes('${')) throw new Error('src/page.css contains "${"; escape it')

// The UI file is emitted as plain source (not inside a literal), so backticks in
// it are fine — but it is inlined, so it must not carry its own imports.
if (/^\s*import\s/m.test(ui)) throw new Error('src/ui.js must not use import: the bundle is a single file')

const head = `/**
 * Agent Channels — browser half.
 *
 * One settings section listing the thirteen agent account channels: which are
 * signed in, what each account's credit balance is, and which of a channel's
 * models the composer's picker should show.
 *
 * Channel operations ride the composition's own \`connection\` RPC at
 * \`/api/channel-pack\`, which the vendored pack registers itself, so no
 * credential ever passes through a route this plugin owns. Only two things are
 * read over HTTP: the pack's mount state, and the browser-opener fallback used
 * when a login popup is blocked.
 *
 * Generated by scripts/build-client.mjs from src/ui.js, src/page.css and
 * src/channels.data.js — edit those, not this file.
 */
window.__ModuleLoader__.load({
  id: 'dsh-agent-connect',
  factory: require => {
    const module = { exports: {} }
    const exports = module.exports
    const React = require('react')
    const { createElement: h, Fragment, useState, useEffect, useMemo, useRef, useCallback } = React

    const NS = 'settings.agentChannels'
    const inject = ['slots', 'locale']
    /** This plugin's own HTTP prefix (the host half registers it). */
    const API = (() => {
      try { return new URL('api/agent-channels', document.baseURI).pathname } catch { return '/api/agent-channels' }
    })()

`

const body = [
  head,
  '    // ══ lifted from dsh-our-free-model (see src/channels.data.js) ══════════',
  data,
  '',
  '    // ══ this plugin ════════════════════════════════════════════════════════',
  ui,
  '',
  '    // ══ styles ═════════════════════════════════════════════════════════════',
  '    const CSS = `',
  css,
  '`',
  '',
  '    // ══ registration ═══════════════════════════════════════════════════════',
  `    /**
     * The shell mirrors the active language onto <html lang>, so a render-time
     * read survives a language switch without owning a subscription.
     */
    function localeTag(ctx) {
      try {
        const snapshot = typeof ctx.locale?.getLocale === 'function' ? ctx.locale.getLocale() : ctx.locale?.getSnapshot?.()
        const value = snapshot?.active ?? ctx.locale?.locale
        return typeof value === 'string' ? value : document.documentElement.lang || 'en'
      } catch { return 'en' }
    }

    function apply(ctx) {
      const t = ctx.locale.bind(NS)
      ctx.effect(() => ctx.locale.register(NS, { zh: DICT.zh, en: DICT.en }), 'agent-channels: dictionaries')

      ctx.effect(() => {
        const style = document.createElement('style')
        style.setAttribute('data-plugin', 'dsh-agent-connect')
        style.textContent = CSS
        document.head.appendChild(style)
        return () => style.remove()
      }, 'agent-channels: styles')

      ctx.slots.inject('settings.section', () => ctx.slots.register({
        name: 'settings.section',
        id: 'agent-channels',
        order: 35,
        label: () => t('nav'),
        locale: NS,
      }, props => h(Page, { ...props, locale: localeTag(ctx), ctx })))
    }

    exports.apply = apply
    exports.inject = inject
    exports.name = 'agent-channels'
    // Headless seams for scripts/smoke-client.mjs.
    exports.__test = { DICT, CHANNEL_PROVIDERS, CHANNEL_CREDITS, Page, useChannelRpc, CSS, formatCredits }
    return module.exports
  },
})
`,
].join('\n')

fs.writeFileSync(outFile, body, 'utf8')
console.log(`wrote ${outFile}`)
console.log(`  ${body.split('\n').length} lines, ${Buffer.byteLength(body)} bytes`)
console.log(`  data ${data.split('\n').length} · ui ${ui.split('\n').length} · css ${css.split('\n').length}`)
